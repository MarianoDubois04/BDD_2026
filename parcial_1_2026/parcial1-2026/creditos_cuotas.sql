
DROP DATABASE IF EXISTS creditos_cuotas;
CREATE DATABASE creditos_cuotas CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE creditos_cuotas;

-- ------------------------------------------------------------
-- 1. CLIENTES
-- ------------------------------------------------------------
CREATE TABLE clientes (
  id_cliente       INT UNSIGNED NOT NULL AUTO_INCREMENT,
  dni              VARCHAR(10)  NOT NULL,
  nombre           VARCHAR(50)  NOT NULL,
  apellido         VARCHAR(50)  NOT NULL,
  email            VARCHAR(120) NULL,
  telefono         VARCHAR(20)  NULL,
  fecha_nacimiento DATE         NOT NULL,
  provincia        VARCHAR(40)  NOT NULL,
  ingreso_mensual  DECIMAL(12,2) NULL,
  score_crediticio SMALLINT UNSIGNED NOT NULL,
  fecha_alta       DATE         NOT NULL,
  estado           ENUM('activo','inactivo','bloqueado') NOT NULL DEFAULT 'activo',
  PRIMARY KEY (id_cliente),
  UNIQUE KEY uq_clientes_dni (dni),
  KEY ix_clientes_provincia (provincia),
  CONSTRAINT ck_clientes_score CHECK (score_crediticio BETWEEN 300 AND 850),
  CONSTRAINT ck_clientes_ingreso CHECK (ingreso_mensual IS NULL OR ingreso_mensual > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 2. COMERCIOS
-- ------------------------------------------------------------
CREATE TABLE comercios (
  id_comercio   INT UNSIGNED NOT NULL AUTO_INCREMENT,
  razon_social  VARCHAR(80)  NOT NULL,
  cuit          VARCHAR(13)  NOT NULL,
  rubro         VARCHAR(40)  NOT NULL,
  provincia     VARCHAR(40)  NOT NULL,
  ciudad        VARCHAR(40)  NOT NULL,
  comision_pct  DECIMAL(5,2) NOT NULL,
  fecha_alta    DATE         NOT NULL,
  activo        TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_comercio),
  UNIQUE KEY uq_comercios_cuit (cuit),
  KEY ix_comercios_rubro (rubro),
  CONSTRAINT ck_comercios_comision CHECK (comision_pct >= 0 AND comision_pct <= 30)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 3. PLANES DE FINANCIACION
-- ------------------------------------------------------------
CREATE TABLE planes_financiacion (
  id_plan          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre           VARCHAR(60)  NOT NULL,
  cantidad_cuotas  TINYINT UNSIGNED NOT NULL,
  tasa_mensual_pct DECIMAL(5,2) NOT NULL,
  coeficiente      DECIMAL(6,4) NOT NULL,  -- multiplicador sobre el capital
  activo           TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_plan),
  UNIQUE KEY uq_planes_nombre (nombre),
  CONSTRAINT ck_planes_cuotas CHECK (cantidad_cuotas > 0),
  CONSTRAINT ck_planes_coef CHECK (coeficiente >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 4. PRESTAMOS
-- ------------------------------------------------------------
CREATE TABLE prestamos (
  id_prestamo        INT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_cliente         INT UNSIGNED NOT NULL,
  id_comercio        INT UNSIGNED NOT NULL,
  id_plan            INT UNSIGNED NOT NULL,
  fecha_otorgamiento DATE          NOT NULL,
  monto_solicitado   DECIMAL(12,2) NOT NULL,  -- capital
  monto_total        DECIMAL(12,2) NOT NULL,  -- capital + interes
  valor_cuota        DECIMAL(12,2) NOT NULL,
  canal              ENUM('app','web','comercio') NOT NULL,
  estado             ENUM('vigente','cancelado','en_mora') NOT NULL,
  PRIMARY KEY (id_prestamo),
  KEY ix_prestamos_cliente (id_cliente),
  KEY ix_prestamos_comercio (id_comercio),
  KEY ix_prestamos_fecha (fecha_otorgamiento),
  CONSTRAINT fk_prestamos_cliente  FOREIGN KEY (id_cliente)  REFERENCES clientes (id_cliente),
  CONSTRAINT fk_prestamos_comercio FOREIGN KEY (id_comercio) REFERENCES comercios (id_comercio),
  CONSTRAINT fk_prestamos_plan     FOREIGN KEY (id_plan)     REFERENCES planes_financiacion (id_plan),
  CONSTRAINT ck_prestamos_monto CHECK (monto_solicitado > 0 AND monto_total >= monto_solicitado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 5. CUOTAS
-- ------------------------------------------------------------
CREATE TABLE cuotas (
  id_cuota          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_prestamo       INT UNSIGNED NOT NULL,
  numero_cuota      TINYINT UNSIGNED NOT NULL,
  fecha_vencimiento DATE          NOT NULL,
  monto_cuota       DECIMAL(12,2) NOT NULL,
  punitorios        DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  estado            ENUM('pendiente','pagada','vencida','parcial') NOT NULL,
  PRIMARY KEY (id_cuota),
  UNIQUE KEY uq_cuotas_prestamo_numero (id_prestamo, numero_cuota),
  KEY ix_cuotas_vencimiento (fecha_vencimiento),
  KEY ix_cuotas_estado (estado),
  CONSTRAINT fk_cuotas_prestamo FOREIGN KEY (id_prestamo)
      REFERENCES prestamos (id_prestamo) ON DELETE CASCADE,
  CONSTRAINT ck_cuotas_monto CHECK (monto_cuota > 0 AND punitorios >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 6. PAGOS  (una cuota puede recibir mas de un pago)
-- ------------------------------------------------------------
CREATE TABLE pagos (
  id_pago        INT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_cuota       INT UNSIGNED NOT NULL,
  fecha_pago     DATE          NOT NULL,
  monto_pagado   DECIMAL(12,2) NOT NULL,
  medio_pago     ENUM('transferencia','debito_automatico','tarjeta','efectivo','billetera_virtual') NOT NULL,
  id_transaccion VARCHAR(20)   NOT NULL,
  PRIMARY KEY (id_pago),
  UNIQUE KEY uq_pagos_transaccion (id_transaccion),
  KEY ix_pagos_cuota (id_cuota),
  KEY ix_pagos_fecha (fecha_pago),
  CONSTRAINT fk_pagos_cuota FOREIGN KEY (id_cuota)
      REFERENCES cuotas (id_cuota) ON DELETE CASCADE,
  CONSTRAINT ck_pagos_monto CHECK (monto_pagado > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ------------------------------------------------------------
-- 7. GESTIONES DE MORA
-- ------------------------------------------------------------
CREATE TABLE gestiones_mora (
  id_gestion    INT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_prestamo   INT UNSIGNED NOT NULL,
  fecha_gestion DATE         NOT NULL,
  canal         ENUM('llamada','whatsapp','email','sms') NOT NULL,
  gestor        VARCHAR(60)  NOT NULL,
  resultado     ENUM('sin_contacto','promesa_pago','pago_realizado','rechazo','renegociacion') NOT NULL,
  observaciones VARCHAR(200) NULL,
  PRIMARY KEY (id_gestion),
  KEY ix_gestiones_prestamo (id_prestamo),
  KEY ix_gestiones_fecha (fecha_gestion),
  CONSTRAINT fk_gestiones_prestamo FOREIGN KEY (id_prestamo)
      REFERENCES prestamos (id_prestamo) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

